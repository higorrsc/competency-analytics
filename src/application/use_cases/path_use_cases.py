"""Use cases for career path definition."""

from src.application.dto.path_dtos import (
    LevelCreateDTO,
    PathCreateDTO,
    PathResponseDTO,
    RequirementCreateDTO,
)
from src.application.use_cases.errors import (
    ConflictError,
    NotFoundError,
    ValidationError,
)
from src.application.use_cases.mappers import map_path
from src.domain.entities.competency_path import CompetencyPath
from src.domain.entities.path_level import PathLevel
from src.domain.exceptions.path_errors import CompetencyPathValidationError
from src.domain.repositories.competency_repository import CompetencyRepository
from src.domain.repositories.path_repository import PathRepository
from src.domain.value_objects.competency_id import CompetencyId
from src.domain.value_objects.competency_requirement import CompetencyRequirement
from src.domain.value_objects.level_id import LevelId
from src.domain.value_objects.path_id import PathId


class CreateCareerPathUseCase:
    """
    Use case for creating a career path with its levels and requirements.

    Orchestration flow:

    1. Validate that every requirement references an existing competency.
    2. Validate that the provided level orders form a contiguous 1..N
       sequence, because the domain requires exactly that sequence.
    3. Build path levels and the aggregate (all domain invariants run).
    4. Persist through the repository.
    5. Return the response DTO.

    Level identifiers are generated by the use case: clients reference levels
    by position, not by identifier, at creation time.
    """

    def __init__(
        self,
        path_repository: PathRepository,
        competency_repository: CompetencyRepository,
    ) -> None:
        """
        Initialize the use case with its repository dependencies.

        Args:
            path_repository: Abstraction for career path persistence.
            competency_repository: Abstraction used to resolve referenced
                competencies.
        """
        self._path_repository = path_repository
        self._competency_repository = competency_repository

    def execute(self, dto: PathCreateDTO) -> PathResponseDTO:
        """
        Create and persist a new career path.

        Args:
            dto: Validated input describing the path, its ordered levels, and
                the competency requirements attached to each level.

        Returns:
            The response DTO describing the stored path.

        Raises:
            NotFoundError: If a requirement references an unknown competency.
            ValidationError: If level orders are not a contiguous 1..N
                sequence.
            ConflictError: If the domain rejects duplicated level names or
                ids.
        """
        requirements_by_order: dict[int, list[CompetencyRequirement]] = {}
        for level in dto.levels:
            requirements_by_order[level.order] = self._build_requirements(
                level.requirements
            )

        self._validate_level_orders(dto.levels)

        path = CompetencyPath(
            id=PathId.generate(),
            name=dto.name,
            description=dto.description,
        )
        for level in sorted(dto.levels, key=lambda item: item.order):
            self._add_level(path, level, requirements_by_order[level.order])
        self._path_repository.save(path)
        return map_path(path)

    def _build_requirements(
        self, dtos: list[RequirementCreateDTO]
    ) -> list[CompetencyRequirement]:
        """
        Resolve requirement DTOs into domain value objects.

        Args:
            dtos: Input requirements for a single path level.

        Returns:
            Domain requirements ready to be attached to a path level.

        Raises:
            NotFoundError: If a requirement references an unknown competency.
        """
        requirements: list[CompetencyRequirement] = []
        for dto in dtos:
            competency_id = CompetencyId(dto.competency_id)
            if self._competency_repository.get_by_id(competency_id) is None:
                raise NotFoundError("Competency", dto.competency_id)
            requirements.append(
                CompetencyRequirement(
                    competency_id=competency_id,
                    minimum_level=dto.minimum_level,
                    weight=dto.weight,
                )
            )
        return requirements

    @staticmethod
    def _validate_level_orders(levels: list[LevelCreateDTO]) -> None:
        """
        Validate that level orders form a contiguous 1..N sequence.

        Args:
            levels: Proposed path levels.

        Raises:
            ValidationError: If orders are not exactly 1..N.
        """
        orders = {level.order for level in levels}
        if orders != set(range(1, len(levels) + 1)):
            raise ValidationError(
                f"levels must have contiguous orders starting at 1; got "
                f"{sorted(orders)}"
            )

    @staticmethod
    def _add_level(
        path: CompetencyPath,
        level: LevelCreateDTO,
        requirements: list[CompetencyRequirement],
    ) -> None:
        """
        Build a path level and attach it to the path.

        Args:
            path: Aggregate under construction.
            level: Input level with its ordered position.
            requirements: Domain requirements already resolved for the level.

        Raises:
            ConflictError: If the domain rejects a duplicated level order,
                name, or identifier.
        """
        path_level = PathLevel(
            id=LevelId.generate(),
            name=level.name,
            order=level.order,
        )
        for requirement in requirements:
            path_level.add_requirement(requirement)
        try:
            path.add_level(path_level)
        except CompetencyPathValidationError as exc:
            raise ConflictError(str(exc)) from exc
